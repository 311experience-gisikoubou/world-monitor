#!/usr/bin/env node
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const arg=process.argv[2]
  ? resolve(process.argv[2])
  : fileURLToPath(new URL('./common-rule-health-audit.mjs', import.meta.url));
const {auditRuleHealth,CONTRACTS}=await import(pathToFileURL(arg).href);
const root=await mkdtemp(join(tmpdir(),'rule-health-selftest-'));
async function put(path,text){await mkdir(join(root,...path.split('/').slice(0,-1)),{recursive:true});await writeFile(join(root,...path.split('/')),text,'utf8');}
const contract={id:'x',required:'TECHNICAL',docs:['RULE.md'],impl:['impl.mjs'],tests:['test.mjs']};
const DUP_PARAGRAPH='This repeated policy paragraph intentionally exceeds the duplicate-detection threshold. It describes the same operational rule in exactly the same words so the inventory can prove that duplicated long rule text is detected across canonical Markdown files without changing either source automatically.';
try{
  await put('RULE.md','# Rule\n\nOrdinary unique contract documentation text used only for the docs-existence check.\n');
  await put('impl.mjs','export const ok=true;\n');
  await put('test.mjs','console.log("pass");\n');
  await put('AGENTS.md','<!-- GENERATED BY test -->\n# Agents\n\nThis generated file is excluded from duplicate-paragraph detection entirely, so its content never contributes to the duplicate inventory even if it repeats wording found elsewhere.\n');
  await put('CORE.md','# Core\n\nOrdinary unique CORE policy text that does not repeat anywhere else in this fixture set, proving ordinary unique CORE/OPERATIONS markdown does not create an accidental duplicate failure.\n');
  const reviewOnlyBody=Array.from({length:520},(_,i)=>'operations line '+i).join('\n');
  await put('OPERATIONS.md','# Operations\n\nOrdinary unique OPERATIONS policy text that does not repeat anywhere else in this fixture set.\n\n'+reviewOnlyBody+'\n');
  await put('PROJECT_COMPLETION.md','# Completion\n');
  await put('.agents/skills/README.md','# Skills\n\n- demo\n');
  await put('.agents/skills/demo/SKILL.md','# Demo\n');
  await put('learnings/INDEX.md','# Index\n\n- L-0001\n');
  await put('learnings/L-0001.md','# Learning\n');
  await put('roles/GPT.md','# Role\n');

  let out=await auditRuleHealth({root,contracts:[contract]});
  assert.equal(out.ok,true);
  assert.equal(out.contracts[0].state,'ENFORCED');
  assert.equal(out.totals.declarationOnly,0);
  assert.equal(out.totals.unindexedLearnings,0);
  assert.equal(out.totals.unlistedSkills,0);
  assert.equal(out.totals.duplicateParagraphs,0);
  assert.equal(out.totals.hardLongFiles,0);
  assert.equal(out.inventory.duplicateParagraphs.some(item=>item.files.includes('AGENTS.md')),false);
  assert.deepEqual(out.limits,{reviewLongFileLines:500,stopLongFileLines:800});
  assert(out.inventory.longFiles.some(x=>x.file==='OPERATIONS.md'));
  assert.equal(out.inventory.hardLongFiles.some(x=>x.file==='OPERATIONS.md'),false);
  assert.equal(out.reviewRecommended,true);

  const activated={...contract,id:'activated',activationMode:'MACHINE_CALL',enforcementScope:'LOCAL_WHEN_INVOKED',activationEvidence:[{path:'RULE.md',contains:'contract documentation'}]};
  out=await auditRuleHealth({root,contracts:[activated]});
  assert.equal(out.ok,true);
  assert.equal(out.contracts[0].state,'ENFORCED');
  assert.equal(out.contracts[0].activationMode,'MACHINE_CALL');
  assert.equal(out.contracts[0].enforcementScope,'LOCAL_WHEN_INVOKED');
  assert.equal(out.contracts[0].activationMissing.length,0);

  const missingTrigger={...activated,activationEvidence:[{path:'RULE.md',contains:'not-present-trigger'}]};
  out=await auditRuleHealth({root,contracts:[missingTrigger]});
  assert.equal(out.ok,false);
  assert.equal(out.contracts[0].state,'DECLARATION_ONLY');
  assert.equal(out.totals.activationFailures,1);
  assert.equal(out.contracts[0].activationMissing[0].reason,'MARKER_MISSING');

  const stagedContract=CONTRACTS.find(c=>c.id==='staged-reality-checks');
  assert(stagedContract,'staged reality contract must be registered');
  assert.equal(stagedContract.required,'TECHNICAL');
  assert(stagedContract.impl.includes('.agents/skills/test-gate/staged-reality-gate.mjs'));
  assert(stagedContract.tests.includes('.agents/skills/test-gate/staged-reality-gate-selftest.mjs'));
  assert(stagedContract.activationEvidence.some(e=>e.path==='tools/portfolio-governance-audit.mjs'&&e.contains==='stagedRealityCurrent'));

  const browserContract=CONTRACTS.find(c=>c.id==='ui-browser-lifecycle');
  assert(browserContract,'ui browser lifecycle contract must be registered');
  assert.equal(browserContract.required,'TECHNICAL');
  assert(browserContract.impl.includes('.agents/skills/test-gate/ui-browser-lifecycle.mjs'));
  assert(browserContract.tests.includes('.agents/skills/test-gate/ui-browser-lifecycle-selftest.mjs'));
  assert(browserContract.activationEvidence.some(e=>e.path==='.agents/skills/test-gate/staged-reality-gate.mjs'&&e.contains==='UI_BROWSER_CLEANUP'));

  const humanVisualContract=CONTRACTS.find(c=>c.id==='human-visual-review-readiness');
  assert(humanVisualContract,'human visual review readiness contract must be registered');
  assert.equal(humanVisualContract.required,'TECHNICAL');
  assert(humanVisualContract.impl.includes('.agents/skills/test-gate/human-visual-review-gate.mjs'));
  assert(humanVisualContract.tests.includes('.agents/skills/test-gate/human-visual-review-gate-selftest.mjs'));
  assert(humanVisualContract.impl.includes('.agents/skills/test-gate/real-device-preparation-gate.mjs'));
  assert(humanVisualContract.tests.includes('.agents/skills/test-gate/real-device-preparation-gate-selftest.mjs'));
  assert(humanVisualContract.activationEvidence.some(e=>e.path==='AGENTS.md'&&e.contains==='HUMAN_VISUAL_REVIEW_READY_REQUIRED=YES'));
  assert(humanVisualContract.activationEvidence.some(e=>e.path==='.agents/skills/test-gate/SKILL.md'&&e.contains==='human-visual-review-gate.mjs'));

  const routingContract=CONTRACTS.find(c=>c.id==='executable-implementation-routing');
  assert(routingContract,'executable implementation routing contract must be registered');
  assert.equal(routingContract.required,'TECHNICAL');
  assert(routingContract.impl.includes('.agents/skills/preflight-audit/implementation-orchestrator.mjs'));
  assert(routingContract.tests.includes('.agents/skills/preflight-audit/implementation-orchestrator-selftest.mjs'));
  const finalAuditActivation=routingContract.activationEvidence.find(e=>e.path==='.agents/skills/final-pr-audit/SKILL.md');
  assert.equal(finalAuditActivation?.contains,'IMPLEMENTATION_ROUTE_RECEIPT_REQUIRED=YES');

  const routingActivation={...contract,id:'routing-activation',activationEvidence:[{path:'.agents/skills/final-pr-audit/SKILL.md',contains:'IMPLEMENTATION_ROUTE_RECEIPT_REQUIRED=YES'}]};
  await put('.agents/skills/final-pr-audit/SKILL.md','# Final audit\n\nIMPLEMENTATION_ROUTE_RECEIPT_REQUIRED=YES\n');
  out=await auditRuleHealth({root,contracts:[routingActivation]});
  assert.equal(out.ok,true);
  assert.equal(out.contracts[0].state,'ENFORCED');
  await put('.agents/skills/final-pr-audit/SKILL.md','# Final audit\n');
  out=await auditRuleHealth({root,contracts:[routingActivation]});
  assert.equal(out.ok,false);
  assert.equal(out.contracts[0].state,'DECLARATION_ONLY');
  assert.equal(out.contracts[0].activationMissing[0].reason,'MARKER_MISSING');

  await rm(join(root,'impl.mjs'));
  out=await auditRuleHealth({root,contracts:[contract]});
  assert.equal(out.ok,false);
  assert.equal(out.contracts[0].state,'DECLARATION_ONLY');
  assert.equal(out.totals.declarationOnly,1);

  await put('impl.mjs','export const ok=true;\n');
  await put('learnings/L-0002.md','# Unindexed\n');
  out=await auditRuleHealth({root,contracts:[contract]});
  assert.equal(out.ok,false);
  assert(out.inventory.unindexedLearnings.includes('learnings/L-0002.md'));

  await put('learnings/INDEX.md','# Index\n\n- L-0001\n- L-0002\n');
  await put('.agents/skills/orphan/SKILL.md','# Orphan\n');
  out=await auditRuleHealth({root,contracts:[contract]});
  assert.equal(out.ok,true);
  assert(out.inventory.unlistedSkills.includes('orphan'));
  assert.equal(out.reviewRecommended,true);

  const longBody=Array.from({length:510},(_,i)=>'line '+i).join('\n');
  await put('CORE.md','# Core\n'+longBody+'\n');
  out=await auditRuleHealth({root,contracts:[contract]});
  assert(out.inventory.longFiles.some(x=>x.file==='CORE.md'));
  assert.equal(out.ok,true);
  assert.equal(out.inventory.hardLongFiles.some(x=>x.file==='CORE.md'),false);

  const hardBody=Array.from({length:810},(_,i)=>'line '+i).join('\n');
  await put('CORE.md','# Core\n'+hardBody+'\n');
  out=await auditRuleHealth({root,contracts:[contract]});
  assert(out.inventory.hardLongFiles.some(x=>x.file==='CORE.md'));
  assert(out.totals.hardLongFiles>=1);
  assert.equal(out.ok,false);
  assert.equal(out.code,'COMMON_RULE_HEALTH_STOP');

  await put('CORE.md','# Core\n\n'+DUP_PARAGRAPH+'\n');
  await put('OPERATIONS.md','# Operations\n\n'+DUP_PARAGRAPH+'\n');
  out=await auditRuleHealth({root,contracts:[contract]});
  assert(out.totals.duplicateParagraphs>=1);
  assert(out.inventory.duplicateParagraphs.some(item=>item.files.includes('CORE.md')&&item.files.includes('OPERATIONS.md')));
  assert.equal(out.inventory.duplicateParagraphs.some(item=>item.files.includes('AGENTS.md')),false);
  assert.equal(out.ok,false);
  assert.equal(out.code,'COMMON_RULE_HEALTH_STOP');


  // Issue #345: a consuming repo cannot contain Foundation's central portfolio
  // coordinator. Verify it in a separately PINNED, real Git Foundation checkout.
  {
    const source=await mkdtemp(join(tmpdir(),'foundation345-central-fixture-'));
    try {
      const {spawnSync}=await import('node:child_process');
      const {readFile,appendFile}=await import('node:fs/promises');
      function git(...args) {
        const r=spawnSync('git',['-C',source,...args],{windowsHide:true,encoding:'utf8'});
        assert.equal(r.status,0,JSON.stringify({args,error:r.stderr}));
        return r.stdout.trim();
      }
      git('init','--quiet');git('config','user.name','Synthetic Test');
      git('config','user.email','synthetic@example.invalid');
      git('remote','add','origin','https://github.com/311experience-gisikoubou/ai-dev-foundation.git');
      await mkdir(join(source,'tools'),{recursive:true});
      const manifest={schemaVersion:1,thisRepository:'311experience-gisikoubou/ai-dev-foundation',projectRootRepository:'311experience-gisikoubou/ai-dev-foundation',repositoryRole:'ROOT'};
      await writeFile(join(source,'PROJECT_CONTEXT.json'),JSON.stringify(manifest)+'\n');
      const toolsFile=join(source,'tools','portfolio-governance-audit.mjs');
      await writeFile(toolsFile,'// collectRuleHealth fixture\n');
      git('add','--','PROJECT_CONTEXT.json','tools/portfolio-governance-audit.mjs');
      git('commit','--quiet','-m','synthetic central source');
      const pinned=git('rev-parse','HEAD');
      const ext={foundationRoot:source,foundationHead:pinned};
      const consumerContract={...contract,id:'consumer-portfo-activation',activationEvidence:[
        {path:'tools/portfolio-governance-audit.mjs',contains:'collectRuleHealth'},
        {path:'RULE.md',contains:'contract documentation'},
      ]};
      await put('CORE.md','# Core\n\nUnique local core policy for external Foundation activation test.\n');
      await put('OPERATIONS.md','# Ops\n\nUnique local operations policy for external Foundation activation test.\n');
      await put('RULE.md','# Rule\n\nLocal contract documentation marker verified in original consumer root.\n');
      let x=await auditRuleHealth({root,contracts:[consumerContract]});
      assert.equal(x.ok,false,'default local strictness must not be relaxed');
      assert.equal(x.contracts[0].activationMissing[0].reason,'FILE_MISSING');
      x=await auditRuleHealth({root,contracts:[consumerContract],...ext});
      assert.equal(x.ok,true);
      assert.equal(x.externalPortfolioSource.head,pinned);
      assert.equal(x.externalPortfolioSource.centralAuditExecuted,false);
      assert.equal(x.contracts[0].activationMissing.length,0);
      assert.equal((await auditRuleHealth({root,contracts:[consumerContract],foundationRoot:source})).code,'FOUNDATION_SOURCE_PIN_REQUIRED');
      assert.equal((await auditRuleHealth({root,contracts:[consumerContract],foundationRoot:source,foundationHead:'f'.repeat(40)})).code,'FOUNDATION_SOURCE_GIT_IDENTITY_MISMATCH');
      git('remote','set-url','origin','https://github.com/311experience-gisikoubou/not-foundation.git');
      assert.equal((await auditRuleHealth({root,contracts:[consumerContract],...ext})).code,'FOUNDATION_SOURCE_GIT_IDENTITY_MISMATCH');
      git('remote','set-url','origin','https://github.com/311experience-gisikoubou/ai-dev-foundation.git');
      await appendFile(toolsFile,'// malicious or newer unchecked change\n');
      assert.equal((await auditRuleHealth({root,contracts:[consumerContract],...ext})).code,'FOUNDATION_SOURCE_DIRTY');
      git('checkout','--','tools/portfolio-governance-audit.mjs');
      await rm(toolsFile);
      assert.equal((await auditRuleHealth({root,contracts:[consumerContract],...ext})).code,'FOUNDATION_SOURCE_FILE_MISSING');
      git('checkout','--','tools/portfolio-governance-audit.mjs');
      await writeFile(join(source,'PROJECT_CONTEXT.json'),JSON.stringify({...manifest,thisRepository:'311experience-gisikoubou/fake'})+'\n');
      assert.equal((await auditRuleHealth({root,contracts:[consumerContract],...ext})).code,'FOUNDATION_SOURCE_REPOSITORY_MISMATCH');
      git('checkout','--','PROJECT_CONTEXT.json');
      // The central tool is present and correctly pinned, but local activation
      // still cannot be skipped.
      await put('RULE.md','# Rule\n\nNo local activation marker.\n');
      x=await auditRuleHealth({root,contracts:[consumerContract],...ext});
      assert.equal(x.ok,false);
      assert.equal(x.contracts[0].activationMissing[0].reason,'MARKER_MISSING');
    } finally {await rm(source,{recursive:true,force:true});}
  }

  console.log('common-rule-health-audit selftest: PASS');
} finally {
  await rm(root,{recursive:true,force:true});
}
