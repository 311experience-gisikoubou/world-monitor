#!/usr/bin/env node
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

export const AGENTS_MAX_BYTES = 16 * 1024;
export const INDEX_TEMPLATE = 'templates/AGENTS.index.md.template';
export const ANTIGRAVITY_TEMPLATE = 'templates/.agents/rules/ai-foundation.md.template';
export const CLAUDE_TEMPLATE = 'templates/.claude/CLAUDE.md.template';
export const GEMINI_TEMPLATE = 'templates/GEMINI.md.template';

async function isFile(path) {
  try { return (await stat(path)).isFile(); } catch { return false; }
}
function normalize(text) {
  return String(text).replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
}
export function coreBody(coreText) {
  const normalized = normalize(coreText);
  return normalized.replace(/^# CORE\.md\n+/, '').trimEnd();
}
export function renderAgents(coreText, indexText) {
  return [
    '<!-- GENERATED BY foundation-sync-audit/entrypoint-renderer.mjs. DO NOT EDIT DIRECTLY. -->',
    '# AGENTS.md',
    '',
    '## Tier 0 — CORE.md から生成',
    '',
    coreBody(coreText),
    '',
    '## Layered common index',
    '',
    normalize(indexText).trim(),
    '',
  ].join('\n');
}
export function renderAntigravity(coreText) {
  return [
    '<!-- GENERATED FROM CORE.md. DO NOT EDIT DIRECTLY. -->',
    '# AI Foundation — Always-on Tier 0',
    '',
    coreBody(coreText),
    '',
    '## Project entry',
    '',
    '- 作業開始時に repository root の `AGENTS.md` と `AGENTS.local.md` を確認する。',
    '- タスク固有の詳細は `AGENTS.md` の索引から必要な文書・skillだけを読む。',
    '- このruleと他の指示が競合する場合、上記Tier 0安全原則を弱めない。',
    '',
  ].join('\n');
}
async function expected(root) {
  const core = await readFile(resolve(root, 'CORE.md'), 'utf8');
  const index = await readFile(resolve(root, INDEX_TEMPLATE), 'utf8');
  return {
    agents: renderAgents(core, index),
    antigravity: renderAntigravity(core),
  };
}
export async function verifyEntrypointSources(rootRaw) {
  const root = resolve(rootRaw);
  const required = [
    'CORE.md', INDEX_TEMPLATE, CLAUDE_TEMPLATE, GEMINI_TEMPLATE,
    'AGENTS.md', ANTIGRAVITY_TEMPLATE,
  ];
  const missing = [];
  for (const rel of required) if (!(await isFile(resolve(root, rel)))) missing.push(rel);
  if (missing.length) return { ok: false, code: 'ENTRYPOINT_SOURCE_MISSING', missing };

  const exp = await expected(root);
  const actualAgents = normalize(await readFile(resolve(root, 'AGENTS.md'), 'utf8'));
  const actualAntigravity = normalize(await readFile(resolve(root, ANTIGRAVITY_TEMPLATE), 'utf8'));
  const claude = normalize(await readFile(resolve(root, CLAUDE_TEMPLATE), 'utf8'));
  const gemini = normalize(await readFile(resolve(root, GEMINI_TEMPLATE), 'utf8'));
  const errors = [];
  if (actualAgents !== normalize(exp.agents)) errors.push('AGENTS_GENERATED_DRIFT');
  if (actualAntigravity !== normalize(exp.antigravity)) errors.push('ANTIGRAVITY_GENERATED_DRIFT');
  const agentsBytes = Buffer.byteLength(actualAgents, 'utf8');
  if (agentsBytes > AGENTS_MAX_BYTES) errors.push('AGENTS_SIZE_LIMIT_EXCEEDED');
  if (!claude.includes('@../AGENTS.md') || !claude.includes('@../AGENTS.local.md')) errors.push('CLAUDE_ENTRY_IMPORT_MISSING');
  if (!gemini.includes('@./AGENTS.md') || !gemini.includes('@./AGENTS.local.md')) errors.push('GEMINI_ENTRY_IMPORT_MISSING');
  return {
    ok: errors.length === 0,
    code: errors.length ? 'ENTRYPOINT_SOURCE_INVALID' : 'ENTRYPOINT_SOURCE_CURRENT',
    agentsBytes,
    agentsMaxBytes: AGENTS_MAX_BYTES,
    errors,
  };
}
export async function writeEntrypoints(rootRaw) {
  const root = resolve(rootRaw);
  const exp = await expected(root);
  const targets = [
    [resolve(root, 'AGENTS.md'), exp.agents],
    [resolve(root, ANTIGRAVITY_TEMPLATE), exp.antigravity],
  ];
  for (const [path, content] of targets) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, 'utf8');
  }
  return verifyEntrypointSources(root);
}
function parseArgs(argv) {
  let root = '.';
  let write = false;
  let pretty = false;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--root' && argv[i + 1]) root = argv[++i];
    else if (argv[i] === '--write') write = true;
    else if (argv[i] === '--check') write = false;
    else if (argv[i] === '--pretty') pretty = true;
    else throw new Error('ARGUMENT_INVALID');
  }
  return { root, write, pretty };
}
async function main() {
  try {
    const args = parseArgs(process.argv.slice(2));
    const result = args.write ? await writeEntrypoints(args.root) : await verifyEntrypointSources(args.root);
    process.stdout.write(JSON.stringify(result, null, args.pretty ? 2 : 0) + '\n');
    if (!result.ok) process.exitCode = 2;
  } catch (error) {
    process.stdout.write(JSON.stringify({ ok: false, code: 'ENTRYPOINT_RENDERER_ERROR', message: error?.message ?? String(error) }) + '\n');
    process.exitCode = 2;
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main();
